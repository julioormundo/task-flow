# Idioma padrão
CURRENT_LANG = "pt"


def set_language(lang_code: str):
    global CURRENT_LANG
    if lang_code in TRANSLATIONS:
        CURRENT_LANG = lang_code


def get_language_label(lang_code: str) -> str:
    return "English" if lang_code == "en" else "Português"


def t(key: str, **kwargs) -> str:
    """Retorna a tradução da chave no idioma atual."""
    value = TRANSLATIONS.get(CURRENT_LANG, {}).get(key, key)
    if kwargs:
        return value.format(**kwargs)
    return value